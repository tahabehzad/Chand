"""Local workspace key adapter, bounded by ADR-012 and AUTH §8.5.

Authority: ADR-012 local-only storage decision; ADR-003 encryption primitive.
Related: P0-T08 development slice; PiiFieldTransformer.
Scope: reads an explicitly provisioned external master; never creates/falls back.
"""

from __future__ import annotations

import hashlib
from pathlib import Path
from uuid import UUID

from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

from app.core.config import get_settings
from app.core.security.pii_transformer import (
    EncryptionContext,
    PiiFieldTransformer,
    PiiKeyUnavailableError,
)

KEY_ID = "workspace-local-v1"
KEY_PATH = Path(__file__).resolve().parents[4] / ".secrets" / "workspace-master.key"


class LocalWorkspaceKeyRegistry:
    """Per-tenant HKDF keys from the manually provisioned local master."""

    def get_key(self, *, tenant_id: UUID, key_id: str) -> bytes:
        if get_settings().app_env != "local" or key_id != KEY_ID:
            raise PiiKeyUnavailableError("Workspace storage key unavailable.")
        try:
            if KEY_PATH.is_symlink() or not KEY_PATH.is_file():
                raise OSError
            master = KEY_PATH.read_bytes()
            ready = KEY_PATH.with_suffix(".ready").read_text(encoding="ascii")
            if ready != hashlib.sha256(master).hexdigest():
                raise OSError
        except OSError:
            raise PiiKeyUnavailableError("Workspace storage key unavailable.") from None
        if len(master) != 32:
            raise PiiKeyUnavailableError("Workspace storage key unavailable.")
        return HKDF(
            algorithm=hashes.SHA256(), length=32, salt=None,
            info=b"pish:local-workspace:v1:" + tenant_id.bytes,
        ).derive(master)


def context(tenant_id: UUID, record_id: UUID, field: str, key_id: str = KEY_ID) -> EncryptionContext:
    """Bind ciphertext to one record and purpose, preventing row/field swaps."""
    return EncryptionContext(
        tenant_id=tenant_id, record_id=record_id, field_name=field, key_id=key_id,
    )


def transformer() -> PiiFieldTransformer:
    """No key is selected/generated by the financial calculation path."""
    return PiiFieldTransformer(LocalWorkspaceKeyRegistry())
